/**
 * [1010] OG 카드(공유 미리보기 이미지) 응답의 CDN 캐시 규칙 — 한 곳에만 둔다.
 *
 * ── 왜 (실측) ──────────────────────────────────────────────────────────────
 * 2026-09-20~22 하루 함수 호출 2위가 `/api/og/complex` 547회다. [1007] 이 응답에
 * `Cache-Control` 을 붙여 1,008 → 547 까지 내렸지만, 남은 547 은 **캐시 미스가 아니라
 * 서로 다른 URL** 이다: 이 라우트의 쿼리에는 단지명·가격·지역·평형 칩이 전부 들어 있어
 * 단지마다(그리고 가격이 바뀔 때마다) URL 이 다르다. 크롤러가 단지 페이지를 훑으며
 * 새 URL 을 하나씩 처음 긁는 것이므로, s-maxage 를 올려도 "첫 1회"는 그대로 남는다.
 * 올려서 줄어드는 것은 **같은 URL 의 재방문 몫**이다(크롤러 재방문 간격 ≈2.2일 —
 * 하루(86,400) 눈금은 재방문마다 오리진 1회와 거의 같았다. 7일이면 그 몫이 사라진다).
 *
 * ── 캐시가 실제로 먹는가 (코드에서 확인한 것) ─────────────────────────────
 * · 캐시 키: Vercel CDN 은 **경로 + 쿼리스트링 전체**를 키로 쓴다. 이 카드들은 쿼리 값
 *   만으로 그림이 결정되므로 URL 이 곧 내용이다 — 같은 URL 이 다른 그림을 낼 수 없다.
 * · 미들웨어: [1007 · V2a-9] 이후 첫 매처에서 `/api/` 가 빠졌다(middleware.ts). 예전에는
 *   문서 분기가 이 응답에 `no-store` 를 덮어써서 캐시가 아예 안 먹었다. 지금은 Origin
 *   헤더가 있거나 `/api/admin` 일 때만 미들웨어가 붙으므로 크롤러 요청에는 붙지 않는다.
 * · `export const revalidate`: searchParams 를 읽는 동적 라우트 핸들러에서는 효력이 없다
 *   (Next 15 에서 GET 핸들러는 기본 비캐시). CDN 이 보는 것은 아래 헤더뿐이다.
 *
 * ── immutable 을 붙여도 되는 근거 ─────────────────────────────────────────
 * 값이 바뀌면 그 값을 담은 URL 도 같이 바뀐다(메타데이터가 URL 을 만든다). 즉 한 URL 의
 * 그림은 영원히 같다 — 내용 주소(content-addressed)다. 그래서 브라우저가 신선한 동안
 * 재검증조차 하지 않게 `immutable` 을 붙인다. **고정 URL 로 스스로 갱신되는 카드
 * (app/api/og/market-card)는 이 상수를 쓰면 안 된다** — 거기 붙이면 한 번 공유된 카드가
 * 영영 안 바뀐다.
 */
export const OG_STATIC_CACHE_CONTROL =
  "public, max-age=604800, s-maxage=604800, stale-while-revalidate=604800, immutable";

/**
 * 같은 URL 의 그림이 시간이 지나면 **바뀌는** OG 카드용(고정 URL 카드 · DB 를 읽어 그리는 카드).
 * `immutable` 을 붙이지 않는다. 하루 눈금 + 7일 SWR — 공유 미리보기는 하루 단위면 충분하고,
 * 만료 뒤에도 옛 그림을 주면서 뒤에서 갱신하므로 미리보기가 비는 순간이 없다.
 */
export const OG_DYNAMIC_CACHE_CONTROL =
  "public, max-age=0, s-maxage=86400, stale-while-revalidate=604800";
