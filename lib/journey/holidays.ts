/** 알려진 공휴일 전체(테스트·점검용 사본) */
export function knownHolidays(): Record<string, string> {
  return { ...KR_HOLIDAYS };
}

function weekday(day: string): number {
  const [y, m, d] = day.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay();
}

function plusOne(day: string): string {
  const [y, m, d] = day.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d + 1)).toISOString().slice(0, 10);
}

/** 공휴일 이름(알려진 해만) — 없으면 null */
export function holidayName(day: string): string | null {
  return KR_HOLIDAYS[day] ?? null;
}

export function isWeekend(day: string): boolean {
  const w = weekday(day);
  return w === 0 || w === 6;
}

/** 쉬는 날인가 — 토·일, 또는 알려진 해의 공휴일·대체공휴일 */
export function isRestDay(day: string): boolean {
  return isWeekend(day) || holidayName(day) !== null;
}

/** 쉬는 날이면 다음 평일까지 미룬다(평일이면 그대로). 설 연휴 + 주말 + 대체공휴일도 넉넉히 넘는 상한 14일. */
export function nextWorkday(day: string): string {
  let cur = day;
  for (let i = 0; i < 14 && isRestDay(cur); i++) cur = plusOne(cur);
  return cur;
}
