-- [1027 · 제안 1 이어서] 신고가 자동 소식 37건의 면적 표기 "26평형" → "전용 26평".
-- 이 숫자는 전용면적 ÷ 3.3 이다. 시장에서 "○○평형"은 공급면적 기준이라(전용 85㎡ = 34평형) "26평형"이라 적으면
-- 한 체급 작은 집으로 읽힌다 — 제목은 ㎡ 없이 "가락삼익맨숀 26평형 27.3억"뿐이었다.
-- 새 글은 lib/market/price-record-copy.ts 가 "전용 N평"으로 적는다. 숫자(㎡·평·금액)는 그대로 두고 말만 고친다.
-- 대상: 제목의 "N평형" 37건 · 본문 줄의 "(N평형)" 175곳(그 밖의 "평형" 글자는 이 글들에 없다 — 2026-10-03 확인).
-- 롤백: '전용 ([0-9]+)평' → '\1평형' 으로 되돌린다(같은 where).
update public.board_posts
set title = regexp_replace(title, '([0-9]+)평형', '전용 \1평', 'g'),
    content = regexp_replace(content, '\(([0-9]+)평형\)', '(전용 \1평)', 'g')
where external_key like 'price-high:%'
  and (title ~ '[0-9]+평형' or content ~ '\([0-9]+평형\)');