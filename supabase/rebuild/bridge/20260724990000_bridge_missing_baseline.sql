-- 뉴스 수집 기록(사이트맵이 읽는다)
create table if not exists public.news_articles (
  id uuid primary key default gen_random_uuid(),
  board_post_id uuid references public.board_posts(id) on delete set null,
  source_url text,
  title text,
  summary text,
  published_at timestamptz,
  collected_date date not null default current_date,
  raw_meta jsonb not null default '{}'::jsonb,
  editorial_rationale text,
  created_at timestamptz not null default now()
);
create unique index if not exists news_articles_source_url_key on public.news_articles (source_url);
alter table public.news_articles enable row level security;
-- 자동화 스크립트 보관(상태 점검이 건수만 센다)
create table if not exists public.automation_scripts (key text primary key, body text not null default '', updated_at timestamptz not null default now());
alter table public.automation_scripts enable row level security;
create table if not exists public.geo_backlog_tmp (id bigint generated by default as identity primary key, payload jsonb, created_at timestamptz not null default now());
alter table public.geo_backlog_tmp enable row level security;
-- 홈 "실거래 N건 · 단지 N곳" 한 줄(집계 갱신 때 채운다)
create table if not exists public.coverage_totals (id integer primary key default 1, tx_count bigint, complex_count bigint, region_count bigint, refreshed_at timestamptz);
alter table public.coverage_totals enable row level security;
-- 시장 온도 스냅샷(자동 게시가 건수만 센다)
create table if not exists public.market_temperature_snapshots (region_code text not null, snapshot_date date not null default current_date, score numeric, payload jsonb not null default '{}'::jsonb, created_at timestamptz not null default now(), primary key (region_code, snapshot_date));
alter table public.market_temperature_snapshots enable row level security;
-- 결제 주기 제약(뒤 마이그레이션이 이 이름을 바꿔 단다)
do $$ begin
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='payments' and column_name='billing')
     and not exists (select 1 from pg_constraint where conname = 'payments_billing_check') then
    alter table public.payments add constraint payments_billing_check check (billing in ('monthly','yearly'));
  end if;
end $$;
create or replace function private.is_admin(p_uid uuid) returns boolean language sql stable security definer set search_path = public, pg_temp as $$ select private.is_admin() $$;
create or replace function public.is_inspection_note_owner(p_note_id uuid) returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select exists (select 1 from public.inspection_notes n where n.id = p_note_id and lower(n.author_email) = lower(coalesce(auth.jwt() ->> 'email', ''))) $$;
create or replace function public.web_vitals_reject_bots() returns trigger language plpgsql as $$ begin return new; end $$;
create or replace function public.cleanup_expired_reset_tokens() returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare n integer; begin delete from public.password_reset_tokens where expires_at < now() - interval '1 day'; get diagnostics n = row_count; return n; end $$;
-- 저장소에 정의가 없는 RPC(코드 호출 모양에 맞춰 다시 지음)
create or replace function public.increment_complex_view(p_complex_id text) returns void language sql security definer set search_path = public, pg_temp as $$
  insert into public.complex_engagement (complex_id, view_count, updated_at) values (p_complex_id, 1, now())
  on conflict (complex_id) do update set view_count = public.complex_engagement.view_count + 1, updated_at = now() $$;
create or replace function public.increment_meeting_members(p_meeting_id uuid) returns void language sql security definer set search_path = public, pg_temp as $$
  update public.meetings set current_members = current_members + 1, updated_at = now() where id = p_meeting_id $$;
create or replace function public.increment_report_downloads(p_report_id uuid) returns void language sql security definer set search_path = public, pg_temp as $$
  update public.reports set downloads = coalesce(downloads, 0) + 1 where id = p_report_id $$;
create unique index if not exists apartment_complexes_source_external_ukey on public.apartment_complexes (source_key, external_id);
create or replace function public.upsert_apartment_complexes(rows jsonb) returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare n integer; begin
  insert into public.apartment_complexes (source_key, external_id, name, address, lawd_cd, metadata, updated_at)
  select r->>'source_key', r->>'external_id', coalesce(r->>'name',''), r->>'address', r->>'lawd_cd', coalesce(r->'metadata','{}'::jsonb), now()
  from jsonb_array_elements(coalesce(rows,'[]'::jsonb)) r where coalesce(r->>'external_id','') <> ''
  on conflict (source_key, external_id) do update set name = excluded.name, address = coalesce(excluded.address, public.apartment_complexes.address),
    lawd_cd = coalesce(excluded.lawd_cd, public.apartment_complexes.lawd_cd), metadata = public.apartment_complexes.metadata || excluded.metadata, updated_at = now();
  get diagnostics n = row_count; return n; end $$;
revoke all on function public.increment_complex_view(text), public.increment_meeting_members(uuid), public.increment_report_downloads(uuid), public.upsert_apartment_complexes(jsonb), public.cleanup_expired_reset_tokens() from public, anon, authenticated;
grant execute on function public.increment_complex_view(text), public.increment_meeting_members(uuid), public.increment_report_downloads(uuid), public.upsert_apartment_complexes(jsonb), public.cleanup_expired_reset_tokens() to service_role;
